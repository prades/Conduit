// The pictures for players (the owner, 2026-11-11: "Yes, do the images next": a picture's address changes only when the picture changes, and the big pictures in a smaller format with no visible loss).
// `node tools/images.js`; tools/stamp.js runs it for every build. For every picture the game loads (img/{cards,cave,evo,fx,hd,props}/*.png, which the art tools bake), it makes:
//   img/<dir>/<name>.webp  a lossless WebP copy (ImageMagick), kept only when it is smaller and every channel of every pixel is the PNG's, the colour under a clear pixel included
//   js/imgmap.js           IMG_MAP: each .png path -> the address the game loads it from (js/config.js imgSrc): the WebP, or the PNG where a WebP is not smaller, with ?v= a fingerprint of the
//                          PNG's bytes, so the address changes when the picture does and not when the build does (a new build used to download every picture again)
//   game.html              its image preloads (the props sheets) at those same addresses
// The PNGs stay the source: bake one, then run this (a picture whose fingerprint is unchanged is not converted again). Do not edit the .webp files or js/imgmap.js by hand.
// Without ImageMagick a changed picture is loaded as its PNG (correct, only bigger) until this is run where ImageMagick is.
// Then it makes the players' page again (tools/bundle.js), which holds js/imgmap.js and game.html's head.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const { execFile, execFileSync } = require('child_process');
const ROOT = path.join(__dirname, '..');
const DIRS = ['cards', 'cave', 'evo', 'fx', 'hd', 'props'];
const MAP_FILE = 'js/imgmap.js';
const PRELOAD = /(<link rel="preload" as="image" href=")(img\/[^"?]+)\.(?:png|webp)\?v=[^"]*(">)/g;
const rd = f => fs.readFileSync(path.join(ROOT, f), 'utf8');

// the first 8 hex of the SHA-1 of a file's bytes
const print = f => crypto.createHash('sha1').update(fs.readFileSync(path.join(ROOT, f))).digest('hex').slice(0, 8);
// every picture the game loads, as its .png path, sorted
function pictures() {
    const out = [];
    for (const d of DIRS) for (const n of fs.readdirSync(path.join(ROOT, 'img', d)).sort()) if (/\.png$/.test(n)) out.push('img/' + d + '/' + n);
    return out;
}
// the map as js/imgmap.js has it now ({} when there is none, or it does not read)
function current() {
    try { const m = rd(MAP_FILE).match(/const IMG_MAP = (\{[\s\S]*?\});/); return m ? JSON.parse(m[1]) : {}; } catch (e) { return {}; }
}
function text(map) {
    const keys = Object.keys(map).sort();
    return '// GENERATED by tools/images.js from the pictures in img/{' + DIRS.join(',') + '}: the address the game loads each one from, by its .png path (js/config.js imgSrc). The lossless WebP copy where it is\n'
        + '// smaller, with a fingerprint of the picture, so an address changes only when its picture does. Do not edit: bake the picture, then run node tools/images.js (node tools/stamp.js runs it).\n'
        + 'const IMG_MAP = {\n' + keys.map((k, i) => '    ' + JSON.stringify(k) + ': ' + JSON.stringify(map[k]) + (i < keys.length - 1 ? ',' : '')).join('\n') + '\n};\n';
}
// game.html with each image preload at the map's address (an error: a preload of a picture the map does not have)
function preloaded(html, map) {
    return html.replace(PRELOAD, (all, a, p, b) => { const to = map[p + '.png']; if (!to) throw new Error('game.html preloads ' + p + ', which is not a picture the game loads'); return a + to + b; });
}
// what the map should be from the files as they are, converting nothing: each picture's fingerprint, its WebP where one is there; and what is stale
function expected() {
    const old = current(), map = {}, stale = [];
    for (const p of pictures()) {
        const v = print(p), w = p.replace(/\.png$/, '.webp'), hasW = fs.existsSync(path.join(ROOT, w)), was = old[p] || '';
        if (!was.endsWith('?v=' + v) || (was.startsWith(w + '?') && !hasW)) stale.push(p);
        map[p] = (was.startsWith(w + '?') && hasW ? w : p) + '?v=' + v;
    }
    return { map, stale, orphans: orphans() };
}
// WebP copies with no picture
function orphans() {
    const out = [];
    for (const d of DIRS) for (const n of fs.readdirSync(path.join(ROOT, 'img', d)).sort()) if (/\.webp$/.test(n) && !fs.existsSync(path.join(ROOT, 'img', d, n.replace(/\.webp$/, '.png')))) out.push('img/' + d + '/' + n);
    return out;
}
function hasMagick() { try { execFileSync('convert', ['-version'], { stdio: 'ignore' }); return true; } catch (e) { return false; } }
const run = (args, enc) => new Promise((res, rej) => execFile('convert', args, { encoding: enc || 'buffer', maxBuffer: 1024 * 1024 * 1024 }, (e, out) => e ? rej(e) : res(out)));
// every channel of every pixel, as 8-bit RGBA
const rgba = f => run([path.join(ROOT, f), '-depth', '8', 'rgba:-']);
// the WebP copy of one picture: { p, w } when it is exact and smaller (written), else { p, why }
async function convert(p) {
    const w = p.replace(/\.png$/, '.webp'), tmp = path.join(ROOT, w + '.tmp');
    try {
        await run([path.join(ROOT, p), '-strip', '-define', 'webp:lossless=true', '-define', 'webp:method=6', '-define', 'webp:exact=true', 'webp:' + tmp]);
        const [a, b] = await Promise.all([rgba(p), run(['webp:' + tmp, '-depth', '8', 'rgba:-'])]);
        if (!a.equals(b)) return { p, why: 'is not exact' };
        const sp = fs.statSync(path.join(ROOT, p)).size, sw = fs.statSync(tmp).size;
        if (sw >= sp) return { p, why: 'is not smaller (' + sw + ' bytes, the PNG ' + sp + ')' };
        fs.renameSync(tmp, path.join(ROOT, w)); return { p, w };
    } catch (e) { return { p, why: 'failed: ' + String(e.message).split('\n')[0] }; }
    finally { try { fs.unlinkSync(tmp); } catch (e) { /* gone */ } }
}
async function write(opts) {
    const log = (opts && opts.log) || (() => {}), E = expected(), map = E.map, magick = hasMagick(), done = [];
    for (const o of E.orphans) { fs.unlinkSync(path.join(ROOT, o)); log('removed ' + o + ' (no picture)'); }
    // what to convert: a changed picture, and (with ImageMagick) one loaded as its PNG, which may have been left so only because ImageMagick was not there (BUNKER BLOOM's: its WebP is bigger)
    const todo = magick ? [...new Set([...E.stale, ...Object.keys(map).filter(p => map[p].startsWith(p + '?'))])] : [];
    if (E.stale.length && !magick) log('ImageMagick not found: ' + E.stale.length + ' changed picture(s) load as their PNG until this is run where it is');
    const q = todo.slice(), N = Math.max(1, Math.min(4, require('os').cpus().length));
    await Promise.all(Array.from({ length: N }, async () => { while (q.length) done.push(await convert(q.shift())); }));
    for (const p of [...new Set([...E.stale, ...todo])]) {
        const r = done.find(d => d.p === p), w = p.replace(/\.png$/, '.webp');
        if (r && r.w) map[p] = w + '?v=' + print(p);
        else { map[p] = p + '?v=' + print(p); try { fs.unlinkSync(path.join(ROOT, w)); } catch (e) { /* none */ } if (r && E.stale.includes(p)) log(p + ': stays a PNG: its WebP ' + r.why); }
    }
    fs.writeFileSync(path.join(ROOT, MAP_FILE), text(map));
    const html = rd('game.html'), next = preloaded(html, map); if (next !== html) fs.writeFileSync(path.join(ROOT, 'game.html'), next);
    return { map, stale: E.stale, converted: done.filter(d => d.w), magick };
}
module.exports = { DIRS, MAP_FILE, pictures, print, current, text, preloaded, expected, orphans, write };
if (require.main === module) {
    write({ log: m => console.log('  ' + m) }).then(r => {
        const all = Object.keys(r.map), webp = all.filter(k => r.map[k].indexOf('.webp?') > 0), mb = n => (n / 1048576).toFixed(1) + ' MB';
        const sizeOf = (k, ext) => fs.statSync(path.join(ROOT, k.replace(/\.png$/, ext))).size, png = all.reduce((n, k) => n + sizeOf(k, '.png'), 0), served = all.reduce((n, k) => n + (webp.includes(k) ? sizeOf(k, '.webp') : sizeOf(k, '.png')), 0);
        console.log('pictures: ' + all.length + ', ' + webp.length + ' loaded as lossless WebP; ' + r.stale.length + ' changed (' + r.converted.length + ' converted); all of them ' + mb(png) + ' as PNG, ' + mb(served) + ' as loaded; ' + MAP_FILE + ' and game.html\'s preloads written');
        const bd = require('./bundle.js').write(); console.log('bundled ' + bd.files.length + ' scripts into dist/conduit.js and wrote play.html (build ' + bd.build + ')');
    }).catch(e => { console.error('images: ' + e.message); process.exit(1); });
}
